type MessageValues = Readonly<Record<string, string | number>>;

export function formatMessage(message: string, values: MessageValues) {
  return message.replace(/\{(\w+)\}/g, (placeholder, name) => String(values[name] ?? placeholder));
}

export type PageCopy = (english: string) => string;

export function pageCopy(zh: boolean): PageCopy {
  if (!zh) return english => english;
  return english => {
    const message = zhMessages[english] ?? english;
    const parameter = message.match(/\{(\w+)\}/)?.[1];
    const value = english.match(/[\d,.]*\d/)?.[0];
    return parameter && value ? formatMessage(message, { [parameter]: value }) : message;
  };
}

export function playLabel(title: string, zh: boolean) {
  const english = formatMessage("Play {title}", { title });
  if (!zh) return english;
  return zhMessages[english] ?? formatMessage("播放 {title}", { title: pageCopy(zh)(title) });
}

