export function specificationValue(value: string, zh: boolean) {
  if (!zh) return value;
  for (const [pattern, template, parameter] of zhSpecificationFormats) {
    const match = value.match(pattern);
    if (match) return formatMessage(template, { [parameter]: match[1] });
  }
  return zhMessages[value] ?? value;
}
