import fs from "node:fs";
import ts from "typescript";

const input = "app/components/our-solution-ja.tsx";
const output = "app/components/our-solution-zh.tsx";
const catalog = JSON.parse(fs.readFileSync("lib/i18n/solutions-zh.json", "utf8"));
const source = fs.readFileSync(input, "utf8");
const tree = ts.createSourceFile(input, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
const cjk = /[\u3040-\u30ff\u3400-\u9fff]/;
const token = /ZXQ(\d+)QXZ/g;
const edits = [];
const missing = new Set();
const escapeTemplate = (value) => value.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");
const localize = (value, renderTranslation = (translation) => translation) => {
  const key = value.trim();
  if (!cjk.test(key)) return value;
  if (!Object.hasOwn(catalog, key)) {
    missing.add(key);
    return value;
  }
  return value.replace(key, () => renderTranslation(catalog[key]));
};

function visit(node) {
  if (ts.isTemplateExpression(node) && [node.head, ...node.templateSpans.map(span => span.literal)].some(part => cjk.test(part.text))) {
    const key = node.head.text + node.templateSpans.map((span, i) => `ZXQ${i}QXZ${span.literal.text}`).join("");
    const translated = localize(key);
    const matches = [...translated.matchAll(token)];
    const indices = matches.map(match => Number(match[1]));
    if (new Set(indices).size !== node.templateSpans.length || indices.length !== node.templateSpans.length || indices.some(i => i >= node.templateSpans.length)) {
      throw Error("Invalid interpolation placeholders in: " + key);
    }
    let next = "`";
    let end = 0;
    for (const match of matches) {
      next += escapeTemplate(translated.slice(end, match.index));
      const expression = node.templateSpans[Number(match[1])].expression;
      const childEdits = [];
      const start = edits.length;
      visit(expression);
      childEdits.push(...edits.splice(start));
      next += "${" + apply(source.slice(expression.getStart(tree), expression.end), childEdits, expression.getStart(tree)) + "}";
      end = match.index + match[0].length;
    }
    next += escapeTemplate(translated.slice(end)) + "`";
    edits.push([node.getStart(tree), node.end, next]);
    return;
  }
  if (ts.isStringLiteral(node) && cjk.test(node.text)) {
    edits.push([node.getStart(tree), node.end, JSON.stringify(localize(node.text))]);
  } else if (ts.isNoSubstitutionTemplateLiteral(node) && cjk.test(node.text)) {
    edits.push([node.getStart(tree), node.end, "`" + escapeTemplate(localize(node.text)) + "`"]);
  } else if (ts.isJsxText(node) && cjk.test(node.text)) {
    const text = localize(node.text, (translation) => translation
      .replaceAll("{", "&#123;")
      .replaceAll("}", "&#125;")
      .replaceAll("<", "&lt;")
      .replaceAll("\n", "<br />"));
    edits.push([node.pos, node.end, text]);
  }
  ts.forEachChild(node, visit);
}

function apply(text, changes, offset = 0) {
  return changes.sort((a, b) => b[0] - a[0]).reduce((result, [start, end, value]) => result.slice(0, start - offset) + value + result.slice(end - offset), text);
}

visit(tree);
if (missing.size) throw Error("Missing Traditional Chinese copy:\n" + [...missing].join("\n"));

let result = apply(source, edits);
result = result.replaceAll("OurSolutionJa", "OurSolutionZh")
  .replaceAll('lang="ja"', 'lang="zh-TW"')
  .replaceAll('document.documentElement.lang = "ja"', 'document.documentElement.lang = "zh-TW"')
  .replaceAll('"ja-JP"', '"zh-TW"')
  .replaceAll("/ja/", "/zh/")
  .replace("Japanese edition of Our Solution. Keep its market behavior in sync with the English edition.", "Generated by scripts/generate-zh-solutions.mjs from the full Japanese layout and the Traditional Chinese catalog.");
fs.writeFileSync(output, result);
